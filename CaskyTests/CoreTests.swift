    private let casks = Data(#"""
    [
      {"token": "zoom", "name": ["Zoom"], "desc": "Video calls", "homepage": "https://zoom.us", "deprecated": false, "disabled": false,
       "artifacts": [{"uninstall": [{"pkgutil": "us.zoom"}]}, {"pkg": ["zoom.pkg"]}]},
