@Suite struct InstallPlanTests {
    private func ref(_ raw: String) throws -> Ref { try Ref(parsing: raw) }

    @Test func ordersTapsFormulaeCasksAppsWithAdminLast() throws {
        let zoom = Item.cask(try ref("zoom"))
        let tool = Item.cask(try ref("a/b/tool"))
        let selection: [Item] = [
            .mas(id: 7, name: "App"),
            zoom,
            .cask(try ref("firefox")),
            .formula(try ref("git")),
            tool,
        ]
        let plan = InstallPlan(selection: selection, installed: InstalledState(), needsAdmin: [zoom])

        #expect(plan.steps.map(\.action) == [
            .tap("a/b"),
            .install(.formula(.masTool)),
            .install(.formula(try ref("git"))),
            .install(.cask(try ref("firefox"))),
            .install(tool),
            .install(zoom),
            .install(.mas(id: 7, name: "App")),
        ])
        #expect(plan.steps.first { $0.action == .install(tool) }?.prerequisites == [.tap("a/b")])
        #expect(plan.steps.last?.prerequisites == [.install(.formula(.masTool))])
    }

    @Test func skipsInstalledItemsAndExistingTaps() throws {
        var installed = InstalledState()
        installed.casks = ["firefox"]
        installed.formulae = ["mas"]
        installed.taps = ["a/b"]
        let selection: [Item] = [.cask(try ref("firefox")), .cask(try ref("a/b/tool")), .mas(id: 7, name: "App")]

        let plan = InstallPlan(selection: selection, installed: installed)

        #expect(plan.alreadyInstalled == [.cask(try ref("firefox"))])
        #expect(plan.steps.map(\.action) == [.install(.cask(try ref("a/b/tool"))), .install(.mas(id: 7, name: "App"))])
        #expect(plan.steps.allSatisfy { $0.prerequisites.isEmpty })
    }

    @Test func dedupesTapsAndSelection() throws {
        let tool = Item.cask(try ref("a/b/one"))
        let plan = InstallPlan(selection: [tool, .formula(try ref("a/homebrew-b/two")), tool], installed: InstalledState())
        #expect(plan.steps.map(\.action) == [
            .tap("a/b"),
            .install(.formula(try ref("a/b/two"))),
            .install(tool),
        ])
    }

    @Test func emptyWhenEverythingIsInstalled() throws {
        var installed = InstalledState()
        installed.formulae = ["git"]
        let plan = InstallPlan(selection: [.formula(try ref("git"))], installed: installed)
        #expect(plan.steps.isEmpty)
        #expect(plan.alreadyInstalled.count == 1)
    }
}

