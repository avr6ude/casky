        #expect(state.requestedFormulae == ["git"])
        #expect(state.snapshot() == [
            .formula(try Ref(parsing: "git")),
            .cask(try Ref(parsing: "charmbracelet/tap/mods")),
            .cask(try Ref(parsing: "firefox")),
            .mas(id: 937984704, name: #"Amph {etamine} "x""#),
