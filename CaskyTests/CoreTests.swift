    @Test func decodesHomebrewTapsAndMas() throws {
        let brewInfo = Data(#"""
        {"formulae": [{"name": "git", "full_name": "git", "installed": [{"installed_on_request": true}]},
                      {"name": "pcre2", "full_name": "pcre2", "installed": [{"installed_on_request": false}]},
